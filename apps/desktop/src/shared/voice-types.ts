/**
 * The types of the voice assistant (spec §15, §19).
 *
 * The file is shared by the main process (the voice service), the
 * preload bridge and the renderer (the composer and the settings). It
 * must never import Node.js or Electron runtime APIs so it stays usable
 * in the sandboxed renderer.
 *
 * The rules of the privacy of the voice are part of the contract:
 *
 *  - the audio is recorded in the renderer, but it is only ever sent to
 *    the main process,
 *  - a local engine receives the audio over a pipe, so nothing is
 *    written to the disk,
 *  - a cloud engine needs the approval of the user for *this*
 *    recording, and the local-only mode blocks it completely.
 */

/** The engine that recognises the speech. */
export type SpeechEngine = 'none' | 'local' | 'cloud';

/** The state of a recording or of a recognition. */
export type VoiceState =
  | 'idle'
  | 'recording'
  | 'processing'
  | 'error';

/** The settings of the voice assistant. */
export interface VoiceSettings {
  /** False when the voice assistant is switched off completely. */
  enabled: boolean;
  /** The engine that recognises the speech. */
  engine: SpeechEngine;
  /** The text that is spoken is read aloud. */
  readAloud: boolean;
  /** The name of the voice of the operating system (empty = the default). */
  voice: string;
  /** The speed of the speech (0.5 … 2). */
  rate: number;
  /** The key that starts the push-to-talk recording. */
  pushToTalkKey: string;
  /** The path of the local speech engine (an executable). */
  enginePath: string;
  /** The arguments of the local speech engine. */
  engineArgs: string[];
  /** The speech model that the local engine uses. */
  modelId: string;
  /** The maximum length of one recording (seconds). */
  maxRecordingSeconds: number;
  /** True when the code blocks of an answer are read aloud too. */
  readCodeBlocks: boolean;
}

/** The settings of the voice assistant when nothing was changed yet. */
export function defaultVoiceSettings(): VoiceSettings {
  return {
    enabled: false,
    engine: 'none',
    readAloud: false,
    voice: '',
    rate: 1,
    pushToTalkKey: 'Control+Shift+V',
    enginePath: '',
    engineArgs: [],
    modelId: '',
    maxRecordingSeconds: 60,
    readCodeBlocks: false,
  };
}

/** The state of the voice assistant. */
export interface VoiceStatus {
  /** The state of the recording. */
  state: VoiceState;
  /** The id of the session (empty when nothing is running). */
  sessionId: string;
  /** The message for the user (honest, never a placeholder). */
  message: string;
  /** The seconds that the current recording is running. */
  elapsedSeconds: number;
}

/** One speech model that can be downloaded. */
export interface VoiceModelInfo {
  /** The id of the model ("tiny", "base", "small"). */
  id: string;
  /** The name that is shown. */
  name: string;
  /** The size of the download (bytes). */
  sizeBytes: number;
  /** True when the model is on the disk. */
  installed: boolean;
  /** The size of the file on the disk (bytes). */
  installedBytes?: number;
  /** The path of the file (only when it is installed). */
  path?: string;
}

/** The state of a download of a speech model. */
export type VoiceDownloadState =
  | 'starting'
  | 'downloading'
  | 'success'
  | 'cancelled'
  | 'error';

/** The progress of the download of a speech model. */
export interface VoiceModelProgress {
  /** The id of the download (generated by the main process). */
  downloadId: string;
  /** The id of the model. */
  modelId: string;
  /** The state of the download. */
  state: VoiceDownloadState;
  /** The message for the user. */
  message: string;
  /** The bytes that were transferred. */
  completedBytes?: number;
  /** The bytes that are expected. */
  totalBytes?: number;
  /** The share that was transferred (0 … 100). */
  percent?: number;
  /** The speed of the transfer (bytes per second). */
  bytesPerSecond?: number;
  /** True when the download is over. */
  done: boolean;
}

/** The result of a recognition. */
export interface VoiceTranscript {
  /** The recognised text. */
  text: string;
  /** True when the engine reported an error. */
  error?: string;
}

/** The maximum length of one recording (seconds). */
export const MAX_RECORDING_SECONDS = 60;
/** The maximum number of bytes of one recording (16 kHz, mono, 16 bit). */
export const MAX_AUDIO_BYTES = 4 * 1024 * 1024;
/** The sample rate that the speech engines expect. */
export const SPEECH_SAMPLE_RATE = 16000;
/** The maximum length of the transcript that is returned. */
export const MAX_TRANSCRIPT_CHARS = 8000;
