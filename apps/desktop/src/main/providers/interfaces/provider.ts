/**
 * The provider interface (spec §11.2).
 *
 * Every provider — local or cloud — implements this interface, so the
 * chat panel and the router never depend on a specific service.
 *
 * The interface is deliberately small: listing models, checking the
 * connection and streaming a chat completion. Tool calls and file access
 * belong to Milestone 5 and are not part of this interface yet.
 */
import type {
  AIStreamEvent,
  AiResult,
  ChatMessage,
  ChatOptions,
  ProviderCapabilities,
  ProviderModel,
  ProviderStatus,
} from '../../../shared/ai-types';

/**
 * A tool the model may call.
 *
 * The tools are an optional capability: a provider that reports
 * `toolCalls: false` never receives them and never returns a tool
 * call.
 */
export interface ProviderTool {
  /** The id of the tool. */
  name: string;
  /** What the tool does. */
  description: string;
  /** The parameters of the tool (a JSON schema). */
  parameters: Record<string, unknown>;
}

/** The request a provider receives. */
export interface ProviderChatRequest {
  /** The id of the request (generated by the main process). */
  requestId: string;
  /** The messages of the conversation. */
  messages: ChatMessage[];
  /** The options of the request (model, temperature, …). */
  options: ChatOptions;
  /**
   * The tools the model may call.
   *
   * The provider only receives them when it reports the capability
   * `toolCalls` (spec §11.1).
   */
  tools?: ProviderTool[];
  /**
   * Aborts the request.
   *
   * The provider must stop the underlying network request when the signal
   * fires — a cancelled request must not keep running in the background.
   */
  signal: AbortSignal;
}

/** A provider of AI models. */
export interface AIProvider {
  /** The stable id of the provider ("ollama", "openai-compatible", …). */
  readonly id: string;
  /** The display name. */
  readonly name: string;
  /** 'local' providers never send anything off the machine. */
  readonly kind: 'local' | 'cloud';

  /** What the provider can actually do. */
  getCapabilities(): ProviderCapabilities;

  /** The models the provider offers (installed models for a local one). */
  listModels(): Promise<AiResult<ProviderModel[]>>;

  /** Checks whether the provider can be reached right now. */
  checkConnection(): Promise<ProviderStatus>;

  /**
   * Streams a chat completion.
   *
   * The generator yields the normalized events; it ends after the `finish`
   * or `error` event.
   */
  chat(request: ProviderChatRequest): AsyncIterable<AIStreamEvent>;
}
